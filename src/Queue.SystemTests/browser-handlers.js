async page => {
  const errors = [];
  let catalogueRequests = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().endsWith('/handlers')) catalogueRequests++; });
  await page.reload();
  await page.locator('#provider').selectOption('sqlite');
  await page.waitForFunction(() => document.getElementById('handlers-status').textContent.startsWith('4 registered'));
  const observedRequests = catalogueRequests;
  // A snapshot arrives every two seconds. It must not trigger another catalogue request.
  await page.waitForTimeout(2500);
  if (catalogueRequests !== observedRequests) throw new Error('Catalogue was fetched during routine snapshot polling.');
  await page.locator('#open-enqueue').click();
  await page.getByRole('button', { name:'Success', exact:true }).click();
  if (await page.locator('#command').inputValue() !== 'demo.echo.v1') throw new Error('Registered example was not selected.');
  if (!(await page.locator('#handler-details').textContent()).includes('no business side effects')) throw new Error('Declaration missing.');
  await page.getByRole('button', { name:'Enqueue command', exact:false }).click();
  await page.waitForFunction(() => document.getElementById('notice').textContent.startsWith('Enqueued '));
  const catalogue = await page.evaluate(async () => (await fetch('/api/sqlite/groups/default/handlers')).json());
  const injected = JSON.parse(JSON.stringify(catalogue));
  injected.handlers.push({ command:'custom.sample.v1', displayName:'Catalogue-only sample', description:'<img src=x onerror="window.handlerExecuted=true">',
    payloadMediaType:'text/plain', examplePayload:'<script>window.handlerExecuted=true</script>', duplicateHandling:'Unspecified',
    duplicateHandlingNotes:'No protection declared.' });
  await page.route('**/api/sqlite/groups/default/handlers', route => route.fulfill({json:injected}));
  await page.locator('#handlers-refresh').click();
  await page.waitForFunction(() => document.getElementById('handlers-status').textContent.startsWith('5 registered'));
  await page.locator('#open-enqueue').click();
  await page.locator('#handler-picker').selectOption('custom.sample.v1');
  if (await page.locator('#payload').inputValue() !== injected.handlers[4].examplePayload) throw new Error('Dynamic payload was not loaded.');
  if (await page.locator('#handler-details img, #handler-details script').count()) throw new Error('Handler metadata was rendered as HTML.');
  if (await page.evaluate(() => window.handlerExecuted)) throw new Error('Handler metadata executed.');
  await page.keyboard.press('Escape');
  await page.unroute('**/api/sqlite/groups/default/handlers');
  let release, started;
  const gate = new Promise(resolve => { release = resolve; });
  const requested = new Promise(resolve => { started = resolve; });
  await page.route('**/api/sqlite/groups/default/handlers', async route => { started(); await gate; await route.fulfill({json:catalogue}); });
  await page.locator('#handlers-refresh').click();
  await requested;
  await page.locator('#queue-group').selectOption('many-email');
  await page.waitForFunction(() => document.getElementById('handlers-status').textContent.startsWith('2 registered'));
  const lateResponse = page.waitForResponse(response => response.url().endsWith('/default/handlers'));
  release(); await lateResponse;
  await page.waitForFunction(() => document.getElementById('handlers-list').textContent.includes('email.batch.v1'));
  if ((await page.locator('#handlers-list').textContent()).includes('demo.echo.v1')) throw new Error('Late response replaced the selected catalogue.');
  const protectedCard = page.locator('#handlers-list .handler-card').filter({hasText:'email.batch.protected.v1'});
  if (await protectedCard.count() !== 1) throw new Error('Protected email handler is missing.');
  if (!(await protectedCard.textContent()).includes('Durable reservation; uncertain sends require review')) throw new Error('Protected handler declaration missing.');
  await page.unroute('**/api/sqlite/groups/default/handlers');
  await page.locator('#open-enqueue').click();
  if (!(await page.locator('#handler-details').textContent()).includes('No duplicate protection')) throw new Error('Email duplicate declaration missing.');
  if (!(await page.locator('#handler-details').textContent()).includes('Retries resend the whole batch')) throw new Error('Email behavior notes missing.');
  await page.locator('#email-count').fill('12');
  await page.locator('#email-batch-size').fill('4');
  await page.locator('#email-form button[type=submit]').click();
  await page.waitForFunction(() => document.getElementById('load-state').textContent.includes('12 / 12 emails'));
  await page.route('**/api/sqlite/groups/many-email/handlers', route => route.fulfill({status:503,json:{error:'Test worker unavailable.'}}));
  await page.locator('#handlers-refresh').click();
  await page.waitForFunction(() => document.getElementById('handlers-status').textContent.includes('unavailable'));
  if (await page.locator('#handlers-list .handler-card').count()) throw new Error('Unavailable catalogue retained stale declarations.');
  await page.locator('#open-enqueue').click();
  if (await page.locator('#email-form button[type=submit]').isEnabled()) throw new Error('Email generation ignored missing registration.');
  await page.keyboard.press('Escape');
  await page.unroute('**/api/sqlite/groups/many-email/handlers');
  await page.locator('#handlers-refresh').click();
  await page.waitForFunction(() => document.getElementById('handlers-status').textContent.startsWith('2 registered'));
  await page.setViewportSize({width:390,height:844});
  await protectedCard.locator(':scope > summary').click();
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile catalogue overflow.');
  await page.screenshot({path:'.artifacts/handler-catalogue-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  await page.locator('#open-enqueue').click();
  await page.screenshot({path:'.artifacts/handler-catalogue-desktop.png',fullPage:true});
  if (errors.length) throw new Error(errors.join('\n'));
  return { catalogue:true, dynamicExamples:true, groupIsolation:true, staleResponses:true, safeText:true, emailGeneration:true, unavailable:true, mobile:true };
}
